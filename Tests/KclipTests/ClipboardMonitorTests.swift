// ClipboardMonitorTests.swift
// Kclip – Open-source keyboard-first clipboard manager
// Unit tests for ClipboardMonitor configuration and lifecycle.

import XCTest
import AppKit
@testable import Kclip

final class ClipboardMonitorTests: XCTestCase {

    // MARK: - Default exclusion list

    func testDefaultExcludedBundleIDs_containsOnePassword() {
        XCTAssertTrue(ClipboardMonitor.defaultExcludedBundleIDs.contains("com.1password.1password"))
    }

    func testDefaultExcludedBundleIDs_containsBitwarden() {
        XCTAssertTrue(ClipboardMonitor.defaultExcludedBundleIDs.contains("com.bitwarden.desktop"))
    }

    func testDefaultExcludedBundleIDs_containsLastPass() {
        XCTAssertTrue(ClipboardMonitor.defaultExcludedBundleIDs.contains("com.lastpass.LastPass"))
    }

    func testDefaultExcludedBundleIDs_containsKeePassXC() {
        XCTAssertTrue(ClipboardMonitor.defaultExcludedBundleIDs.contains("org.keepassxc.keepassxc"))
    }

    func testDefaultExcludedBundleIDs_containsApplePasswords() {
        XCTAssertTrue(ClipboardMonitor.defaultExcludedBundleIDs.contains("com.apple.Passwords"))
    }

    func testDefaultExcludedBundleIDs_hasExpectedCount() {
        // 11 known password managers (including Apple Passwords)
        XCTAssertEqual(ClipboardMonitor.defaultExcludedBundleIDs.count, 11)
    }

    // MARK: - Start / Stop lifecycle

    func testStart_setsOnNewItem() {
        let monitor = ClipboardMonitor()
        var called = false
        monitor.onNewItem = { _ in called = true }
        monitor.start()
        // Timer is running but hasn't fired yet (0.5s interval)
        monitor.stop()
        // Just verify start/stop don't crash
        XCTAssertFalse(called, "Timer shouldn't have fired immediately")
    }

    func testStop_beforeStart_doesNotCrash() {
        let monitor = ClipboardMonitor()
        monitor.stop() // No-op, should not crash
    }

    func testStart_calledTwice_isNoOp() {
        let monitor = ClipboardMonitor()
        monitor.start()
        monitor.start() // Second call is a no-op
        monitor.stop()
    }

    // MARK: - Size limit

    func testIsWithinSizeLimit_smallStringIsAccepted() {
        XCTAssertTrue(ClipboardMonitor.isWithinSizeLimit("hello"))
        XCTAssertTrue(ClipboardMonitor.isWithinSizeLimit(""))
    }

    func testIsWithinSizeLimit_exactlyAtLimitIsAccepted() {
        let atLimit = String(repeating: "a", count: ClipboardMonitor.maxContentByteCount)
        XCTAssertTrue(ClipboardMonitor.isWithinSizeLimit(atLimit))
    }

    func testIsWithinSizeLimit_oneOverLimitIsRejected() {
        let overLimit = String(repeating: "a", count: ClipboardMonitor.maxContentByteCount + 1)
        XCTAssertFalse(ClipboardMonitor.isWithinSizeLimit(overLimit))
    }

    func testIsWithinSizeLimit_measuresUTF8Bytes_notCharacterCount() {
        // "é" is 1 Character but 2 UTF-8 bytes, so half-the-limit of them exceeds it.
        let multibyte = String(repeating: "é", count: ClipboardMonitor.maxContentByteCount / 2 + 1)
        XCTAssertLessThan(multibyte.count, ClipboardMonitor.maxContentByteCount)
        XCTAssertFalse(ClipboardMonitor.isWithinSizeLimit(multibyte),
                       "size must be measured in UTF-8 bytes, not Character count")
    }

    func testOversizedCount_startsAtZero() {
        let monitor = ClipboardMonitor()
        XCTAssertEqual(monitor.oversizedCount, 0)
    }

    // MARK: - Initial state

    func testExcludedCount_startsAtZero() {
        let monitor = ClipboardMonitor()
        XCTAssertEqual(monitor.excludedCount, 0)
    }

    func testLastExcludedApp_startsNil() {
        let monitor = ClipboardMonitor()
        XCTAssertNil(monitor.lastExcludedApp)
    }

    // MARK: - Privacy / own-write markers

    func testMarker_concealedTypeIsSkipped() {
        let types: [NSPasteboard.PasteboardType] = [.string, .init("org.nspasteboard.ConcealedType")]
        XCTAssertTrue(ClipboardMonitor.hasPrivacyMarker(types))
    }

    func testMarker_transientAndAutoGeneratedAreSkipped() {
        XCTAssertTrue(ClipboardMonitor.hasPrivacyMarker([.string, .init("org.nspasteboard.TransientType")]))
        XCTAssertTrue(ClipboardMonitor.hasPrivacyMarker([.string, .init("org.nspasteboard.AutoGeneratedType")]))
    }

    /// Own writes are skipped through a separate check so they are not
    /// counted as privacy exclusions.
    func testMarker_ownWriteIsDetectedSeparatelyFromPrivacy() {
        let types: [NSPasteboard.PasteboardType] = [.string, ClipboardMonitor.ownWriteMarkerType]
        XCTAssertTrue(ClipboardMonitor.isOwnWrite(types))
        XCTAssertFalse(ClipboardMonitor.hasPrivacyMarker(types))
    }

    func testMarker_plainTextIsCaptured() {
        XCTAssertFalse(ClipboardMonitor.hasPrivacyMarker([.string, .rtf]))
        XCTAssertFalse(ClipboardMonitor.hasPrivacyMarker(nil))
        XCTAssertFalse(ClipboardMonitor.isOwnWrite([.string, .rtf]))
        XCTAssertFalse(ClipboardMonitor.isOwnWrite(nil))
    }

    /// Kclip's own writes (paste / copy-only) must carry the marker the monitor
    /// skips — otherwise each paste re-captures the item (duplicating pinned ones).
    func testCopyToPasteboard_tagsOwnWrite() {
        let pasteboard = NSPasteboard(name: .init("cc.kclip.tests.pasteboard"))
        defer { pasteboard.releaseGlobally() }

        PasteHelper.copyToPasteboard("hello", pasteboard: pasteboard)

        XCTAssertEqual(pasteboard.string(forType: .string), "hello")
        XCTAssertTrue(ClipboardMonitor.isOwnWrite(pasteboard.types))
    }
}
